"""
02_data_cleaning.py
===================
ETL cleaning layer for the Telecom Big Data Analytics Platform.

Reads  : data/raw/telecom_customers.csv       (dirty, as generated by Step 01)
Writes : data/processed/telecom_cleaned.csv   (clean, feature-engineered)

Run from project root:  python scripts/02_data_cleaning.py
"""
from __future__ import annotations

import sys
from pathlib import Path
from typing import Final

import numpy as np
import pandas as pd

# --------------------------------------------------------------------------- #
# Paths
# --------------------------------------------------------------------------- #
PROJECT_ROOT: Final[Path] = Path(__file__).resolve().parents[1]
RAW_PATH: Final[Path] = PROJECT_ROOT / "data" / "raw" / "telecom_customers.csv"
CLEAN_PATH: Final[Path] = PROJECT_ROOT / "data" / "processed" / "telecom_cleaned.csv"

# --------------------------------------------------------------------------- #
# Step 1 — Load
# --------------------------------------------------------------------------- #
def load_raw(path: Path) -> pd.DataFrame:
    """Load raw CSV with explicit dtype hints to avoid silent mis-casting."""
    if not path.exists():
        print(f"ERROR: raw file not found at {path}", file=sys.stderr)
        sys.exit(1)

    df = pd.read_csv(
        path,
        dtype={
            "customer_id": str,
            "region":       str,
            "plan_type":    str,
        },
    )
    print(f"Loaded  : {len(df):,} rows  |  {df.shape[1]} columns")
    return df


# --------------------------------------------------------------------------- #
# Step 2 — Standardise text
# --------------------------------------------------------------------------- #
def fix_casing(df: pd.DataFrame) -> pd.DataFrame:
    """
    Normalise all string categoricals to Title Case.
    'north' -> 'North', 'SOUTH' -> 'South', etc.
    Any value already correct is unaffected.
    """
    for col in ("region", "plan_type"):
        df[col] = df[col].str.strip().str.title()
    return df


# --------------------------------------------------------------------------- #
# Step 3 — Deduplicate
# --------------------------------------------------------------------------- #
def deduplicate(df: pd.DataFrame) -> pd.DataFrame:
    """
    Drop exact duplicate rows (same customer_id injected twice in Step 01).
    keep='first' retains the first occurrence and removes subsequent ones.
    """
    before = len(df)
    df = df.drop_duplicates(subset=["customer_id"], keep="first").reset_index(drop=True)
    removed = before - len(df)
    print(f"Deduped : removed {removed:,} duplicate rows  |  {len(df):,} remain")
    return df


# --------------------------------------------------------------------------- #
# Step 4 — Fix impossible / outlier values BEFORE imputation
# --------------------------------------------------------------------------- #
def fix_outliers(df: pd.DataFrame) -> pd.DataFrame:
    """
    Two classes of bad numeric values:

    Class A — Impossible (physically cannot be real):
        negative monthly_spend  ->  replace with NaN so imputation handles it
        the injected negatives were data entry errors; NaN is the honest label

    Class B — Extreme outliers (physically possible but statistically absurd):
        data_usage_gb > IQR fence  ->  cap at upper fence (Winsorisation)
        We cap, not delete, to preserve the customer record.
    """
    # Class A: negative spend -> NaN (imputation will fill it in Step 5)
    neg_mask = df["monthly_spend"] < 0
    df.loc[neg_mask, "monthly_spend"] = np.nan
    print(f"Outliers: {neg_mask.sum()} negative spend values set to NaN")

    # Class B: IQR fence on data_usage_gb
    q1 = df["data_usage_gb"].quantile(0.25)
    q3 = df["data_usage_gb"].quantile(0.75)
    iqr = q3 - q1
    upper_fence = q3 + 3.0 * iqr   # 3× IQR is a conservative enterprise-standard fence
    extreme_mask = df["data_usage_gb"] > upper_fence
    df.loc[extreme_mask, "data_usage_gb"] = upper_fence
    print(f"Outliers: {extreme_mask.sum()} extreme data_usage_gb values capped at {upper_fence:.2f} GB")

    return df


# --------------------------------------------------------------------------- #
# Step 5 — Impute missing values
# --------------------------------------------------------------------------- #
def impute_nulls(df: pd.DataFrame) -> pd.DataFrame:
    """
    Median imputation for all numeric columns with nulls.
    Median is preferred over mean because spend/usage distributions are
    right-skewed (lognormal) — mean is pulled upward by heavy users;
    median represents the typical customer.

    Imputation is done AFTER outlier fixing so the median itself isn't
    corrupted by the impossible values we just neutralised.
    """
    numeric_cols_with_nulls = [
        "tenure_months",
        "monthly_spend",
        "data_usage_gb",
        "signal_quality_score",
    ]
    for col in numeric_cols_with_nulls:
        median_val = df[col].median()
        null_count = df[col].isna().sum()
        df[col] = df[col].fillna(median_val)
        print(f"Imputed : {col}  ->  {null_count} nulls filled with median {median_val:.4f}")

    return df


# --------------------------------------------------------------------------- #
# Step 6 — Correct dtypes
# --------------------------------------------------------------------------- #
def fix_dtypes(df: pd.DataFrame) -> pd.DataFrame:
    """
    After imputation, columns that were float64 due to NaN damage can be
    safely cast back to their intended types.
    np.int64 is used explicitly (not Python int) for Pandas/NumPy consistency.
    """
    int_cols = ["tenure_months", "call_minutes", "sms_count",
                "network_complaints", "contract_end_months", "last_upgrade_months"]
    for col in int_cols:
        df[col] = df[col].round(0).astype(np.int64)

    # churn_flag was always int but round-trip through CSV can make it float
    df["churn_flag"] = df["churn_flag"].astype(np.int64)

    print("Dtypes  : int columns re-cast to int64")
    return df


# --------------------------------------------------------------------------- #
# Step 7 — Feature engineering
# --------------------------------------------------------------------------- #
def engineer_features(df: pd.DataFrame) -> pd.DataFrame:
    """
    Add business-meaningful derived columns.
    All are computed vectorised (no row loops).
    """
    # ARPU — industry-standard alias for monthly spend in telecom reporting
    df["arpu"] = df["monthly_spend"].round(2)

    # Tenure bucket — categorical lifecycle stage for dashboard slicers
    tenure_bins = [0, 12, 36, 60, 9999]
    tenure_labels = ["New (0-12m)", "Developing (13-36m)", "Established (37-60m)", "Loyal (60m+)"]
    df["tenure_bucket"] = pd.cut(
        df["tenure_months"],
        bins=tenure_bins,
        labels=tenure_labels,
        right=True,
    )

    # Data intensity — usage relative to voice activity
    # +1 in denominator prevents division by zero for silent customers
    df["data_intensity"] = (df["data_usage_gb"] / (df["call_minutes"] + 1)).round(4)

    # Complaint rate — normalised by tenure to make it comparable across cohorts
    df["complaint_rate"] = (df["network_complaints"] / (df["tenure_months"] + 1)).round(4)

    # High-value binary flag — top 25% of spenders
    spend_75th = df["monthly_spend"].quantile(0.75)
    df["is_high_value"] = (df["monthly_spend"] >= spend_75th).astype(np.int64)

    # CLV estimate — simplified but credible business metric
    # Churn probability proxy: normalise signal quality inversely + complaint rate
    churn_proxy = np.clip(
        (5.0 - df["signal_quality_score"]) / 4.0 + df["complaint_rate"] * 0.5,
        0.01,
        0.99,
    )
    df["clv_estimate"] = (df["monthly_spend"] * df["tenure_months"] * (1.0 - churn_proxy)).round(2)

    print(f"Features: 6 new columns added  "
          f"(arpu, tenure_bucket, data_intensity, complaint_rate, is_high_value, clv_estimate)")
    return df


# --------------------------------------------------------------------------- #
# Step 8 — Validate and save
# --------------------------------------------------------------------------- #
def validate(df: pd.DataFrame) -> None:
    """
    Final sanity checks before writing to disk.
    Raises ValueError if any critical invariant is broken.
    These checks mirror what a data quality gate in a real ETL pipeline would do.
    """
    checks: list[tuple[bool, str]] = [
        (df.isnull().sum().sum() == 0,          "Nulls remain after cleaning"),
        ((df["monthly_spend"] >= 0).all(),       "Negative monthly_spend values remain"),
        ((df["tenure_months"] >= 1).all(),       "Zero or negative tenure_months"),
        ((df["churn_flag"].isin([0, 1])).all(),  "churn_flag contains values other than 0/1"),
        (df["customer_id"].is_unique,            "Duplicate customer_ids remain"),
        (df["region"].str.istitle().all(),       "Region casing not fully normalised"),
    ]
    failed = [msg for passed, msg in checks if not passed]
    if failed:
        for msg in failed:
            print(f"VALIDATION FAILED: {msg}", file=sys.stderr)
        raise ValueError("Cleaned dataset failed validation — see errors above.")

    print("Validate: all checks passed ✓")


def save_clean(df: pd.DataFrame, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(path, index=False)
    print(f"Saved   : {len(df):,} rows  ->  {path}")


# --------------------------------------------------------------------------- #
# Summary report
# --------------------------------------------------------------------------- #
def print_summary(df: pd.DataFrame) -> None:
    print("\n" + "=" * 60)
    print("CLEANED DATASET SUMMARY")
    print("=" * 60)
    print(f"Rows            : {len(df):,}")
    print(f"Columns         : {df.shape[1]}")
    print(f"Churn rate      : {df['churn_flag'].mean():.2%}")
    print(f"Avg ARPU        : €{df['arpu'].mean():.2f}")
    print(f"Avg CLV         : €{df['clv_estimate'].mean():.2f}")
    print(f"High-value cust.: {df['is_high_value'].sum():,}  ({df['is_high_value'].mean():.1%})")
    print(f"Remaining nulls : {df.isnull().sum().sum()}")
    print("\nRegion distribution (should be clean Title Case only):")
    print(df["region"].value_counts().to_string())
    print("\nTenure bucket distribution:")
    print(df["tenure_bucket"].value_counts().sort_index().to_string())
    print("\nColumn dtypes:")
    print(df.dtypes.to_string())
    print("=" * 60)


# --------------------------------------------------------------------------- #
# Entry point
# --------------------------------------------------------------------------- #
def main() -> int:
    try:
        df = load_raw(RAW_PATH)
        df = fix_casing(df)
        df = deduplicate(df)
        df = fix_outliers(df)
        df = impute_nulls(df)
        df = fix_dtypes(df)
        df = engineer_features(df)
        validate(df)
        save_clean(df, CLEAN_PATH)
        print_summary(df)
        print("\nSUCCESS: cleaning pipeline complete.")
    except ValueError:
        return 1
    except (OSError, PermissionError) as exc:
        print(f"ERROR: file I/O failure\n  -> {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())